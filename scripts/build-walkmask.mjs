// Rasterises the authored corridors (scripts/world-corridors.mjs) into the
// bitmask the world walks on.
//
//   node scripts/build-walkmask.mjs          # writes src/lib/walkmask.ts
//   node scripts/build-walkmask.mjs --debug  # also writes preview PNGs
//
// Output is one bit per cell on a GRID_W-wide grid, a few hundred bytes per
// scene, so it costs nothing to ship or to test.
//
// Night shares the day mask: the night art is the same place from the same
// viewpoint under different light, so the ground under the child does not
// move at dusk and every door stays where it was.

import { writeFile, access } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import { CORRIDOR_ART, CORRIDORS } from "./world-corridors.mjs";

const ASSETS = "public/assets/world";
const OUT = "src/lib/walkmask.ts";
const GRID_W = 160;
const DEBUG = process.argv.includes("--debug");

async function maskFor(file, corridors) {
  const meta = await sharp(file).metadata();
  const gridH = Math.round(GRID_W * (meta.height / meta.width));
  const cells = new Uint8Array(GRID_W * gridH);

  // A disc is round on the picture, not on the grid. Both axes scale from the
  // image width so a disc stays circular on screen rather than becoming an
  // ellipse on a portrait map.
  const aspect = meta.height / meta.width;
  for (const stroke of corridors) {
    for (const disc of stroke) {
      const cx = disc.x * GRID_W;
      const cy = disc.y * aspect * GRID_W;
      const r = disc.r * GRID_W;
      const minX = Math.max(0, Math.floor(cx - r));
      const maxX = Math.min(GRID_W - 1, Math.ceil(cx + r));
      const minY = Math.max(0, Math.floor(cy - r));
      const maxY = Math.min(gridH - 1, Math.ceil(cy + r));
      for (let y = minY; y <= maxY; y++) {
        for (let x = minX; x <= maxX; x++) {
          const dx = x + 0.5 - cx, dy = y + 0.5 - cy;
          if (dx * dx + dy * dy <= r * r) cells[y * GRID_W + x] = 1;
        }
      }
    }
  }

  // Every stroke has to reach every other one, or a door ends up in a pocket
  // the child can see but never walk to. Flood from the first disc and report
  // whatever it cannot reach, rather than silently dropping it the way the
  // old largest-region rule did.
  const first = corridors[0][0];
  const start = Math.round(first.y * aspect * GRID_W) * GRID_W + Math.round(first.x * GRID_W);
  const seen = new Uint8Array(cells.length);
  const queue = [start];
  seen[start] = 1;
  let reached = 0;
  while (queue.length) {
    const cell = queue.pop();
    reached++;
    const cx = cell % GRID_W, cy = (cell / GRID_W) | 0;
    for (const [dx, dy] of [[1, 0], [-1, 0], [0, 1], [0, -1]]) {
      const nx = cx + dx, ny = cy + dy;
      if (nx < 0 || ny < 0 || nx >= GRID_W || ny >= gridH) continue;
      const next = ny * GRID_W + nx;
      if (!cells[next] || seen[next]) continue;
      seen[next] = 1;
      queue.push(next);
    }
  }

  let total = 0;
  for (let i = 0; i < cells.length; i++) total += cells[i];

  if (DEBUG) {
    const { data } = await sharp(file)
      .resize(GRID_W, gridH, { fit: "fill", kernel: "cubic" })
      .removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const overlay = Buffer.alloc(GRID_W * gridH * 3);
    for (let i = 0; i < cells.length; i++) {
      const p = i * 3;
      // Magenta = walkable and reachable, yellow = walkable but cut off,
      // dimmed art = not walkable.
      const on = cells[i] && seen[i];
      const cut = cells[i] && !seen[i];
      overlay[p] = on ? 255 : cut ? 255 : data[p] >> 1;
      overlay[p + 1] = on ? 60 : cut ? 240 : data[p + 1] >> 1;
      overlay[p + 2] = on ? 210 : cut ? 40 : data[p + 2] >> 1;
    }
    await sharp(overlay, { raw: { width: GRID_W, height: gridH, channels: 3 } })
      .resize(GRID_W * 5, gridH * 5, { kernel: "nearest" })
      .png().toFile(`/tmp/walkmask-${path.parse(file).name}.png`);
  }

  const bytes = Buffer.alloc(Math.ceil(cells.length / 8));
  for (let i = 0; i < cells.length; i++) {
    if (cells[i]) bytes[i >> 3] |= 1 << (i & 7);
  }
  return {
    width: GRID_W, height: gridH,
    imageWidth: meta.width, imageHeight: meta.height,
    bits: bytes.toString("base64"),
    coverage: total / cells.length,
    stranded: total - reached,
  };
}

const out = {};
let stranded = false;
for (const [scene, corridors] of Object.entries(CORRIDORS)) {
  const art = CORRIDOR_ART[scene];
  if (!art) throw new Error(`${scene}: no art named in CORRIDOR_ART`);
  const file = path.join(ASSETS, `${art}.webp`);
  try {
    await access(file);
  } catch {
    console.warn(`skip ${scene}: no art at ${file}`);
    continue;
  }
  const mask = await maskFor(file, corridors);
  out[scene] = mask;
  if (mask.stranded) stranded = true;
  const note = mask.stranded ? `  ** ${mask.stranded} cells unreachable` : "";
  console.log(`${scene}: ${mask.width}x${mask.height} walkable ${(mask.coverage * 100).toFixed(1)}%${note}`);
}

const body = `// GENERATED by scripts/build-walkmask.mjs — do not edit.
// The source of truth is scripts/world-corridors.mjs; re-run the script after
// changing a corridor or replacing a background.

export interface WalkMask {
  width: number;
  height: number;
  imageWidth: number;
  imageHeight: number;
  /** One bit per cell, row-major, base64 of the packed bytes. */
  bits: string;
}

export const WALK_MASKS: Record<string, WalkMask> = ${JSON.stringify(
  Object.fromEntries(Object.entries(out).map(([key, mask]) => [key, {
    width: mask.width, height: mask.height,
    imageWidth: mask.imageWidth, imageHeight: mask.imageHeight, bits: mask.bits,
  }])), null, 2)};
`;

await writeFile(OUT, body);
console.log(`wrote ${OUT}`);
if (stranded) {
  console.error("\nSome corridors do not join up — fix them in scripts/world-corridors.mjs.");
  process.exit(1);
}
